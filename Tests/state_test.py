def test_schema_contains_descriptions():
    """Validate field descriptions are present in schema."""
    schema = DevelopmentState.schema()
    props = schema.get("properties", {})
    assert props["id"]["description"] == "Unique identifier for the flow execution"
    assert props["requirement"]["description"] == "The original software requirement or feature request"
    assert props["plan"]["description"] == "Technical specification/plan generated by the Architect"
    assert props["database_code"]["description"] == "SQL schemas, ORM models, and database-related code"
    assert props["backend_code"]["description"] == "API endpoints, business logic, and backend services"
    assert props["frontend_code"]["description"] == "UI components, pages, and frontend logic"
    assert props["final_report"]["description"] == "Final audit report with integrated code and validation results"
    assert props["project_name"]["description"] == "Extracted project name from the requirement"
    assert props["status"]["description"] == "Current status of the development flow"


def test_dict_and_json_serialization():
    """Ensure dict and json serialization include all fields and values."""
    state = DevelopmentState(
        requirement="Req",
        plan="Plan",
        database_code="DB",
        backend_code="BE",
        frontend_code="FE",
        final_report="Report",
        project_name="Proj",
        status="done",
    )
    data = state.dict()
    assert data["requirement"] == "Req"
    assert data["plan"] == "Plan"
    assert data["database_code"] == "DB"
    assert data["backend_code"] == "BE"
    assert data["frontend_code"] == "FE"
    assert data["final_report"] == "Report"
    assert data["project_name"] == "Proj"
    assert data["status"] == "done"
    json_str = state.json()
    parsed = json.loads(json_str)
    assert parsed["requirement"] == "Req"
    assert parsed["status"] == "done"


