def test_defaults_and_uuid_generation():
    """Ensure default values are set and id is a valid UUID string."""
    state = DevelopmentState()
    assert isinstance(state.id, str)
    uuid_obj = uuid.UUID(state.id)
    assert str(uuid_obj) == state.id
    assert state.requirement == ""
    assert state.plan == ""
    assert state.database_code == ""
    assert state.backend_code == ""
    assert state.frontend_code == ""
    assert state.final_report == ""
    assert state.project_name is None
    assert state.status == "initialized"


def test_unique_ids_for_multiple_instances():
    """Ensure multiple instances generate unique ids."""
    state1 = DevelopmentState()
    state2 = DevelopmentState()
    assert state1.id != state2.id
    assert uuid.UUID(state1.id)
    assert uuid.UUID(state2.id)


